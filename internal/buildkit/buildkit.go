// GeneratedHeader starts every Go file gen emits; only such files are ever deleted.
const GeneratedHeader = "// Code generated by alder"

// StdError is the error LoadChecked returns (alone) when the standard library does not load: an
// internal error of the compiler, not an I/O failure of the app.
type StdError struct{ Err error }

func (e *StdError) Error() string { return e.Err.Error() }

// LoadChecked loads the app in dir (every .alder file under dir/app) plus the already parsed
// modules extra (added after the directory's, under the usual duplicate and cycle rules), and,
// unless a file failed to parse, resolves names and type-checks it. The bag holds every
// diagnostic, sorted. res is nil when the program was not checked (a parse error). ioErrs are the
// I/O failures of reading dir (or a single *StdError); with any, the program must not be used.
func LoadChecked(dir string, extra []*syntax.Module) (prog *names.Program, res *check.Result, bag *diag.Bag, ioErrs []error) {
	return LoadCheckedWith(dir, extra, check.Options{})
}

// LoadCheckedWith is LoadChecked with the checker's options (check.ProgramWith).
func LoadCheckedWith(dir string, extra []*syntax.Module, o check.Options) (prog *names.Program, res *check.Result, bag *diag.Bag, ioErrs []error) {
	std, err := types.LoadStd()
	if err != nil {
		return nil, nil, &diag.Bag{}, []error{&StdError{err}}
	}
	prog, bag, ioErrs = names.Load(dir, std, extra...)
	if len(ioErrs) > 0 {
		return prog, nil, bag, ioErrs
	}
	if !prog.ParseFailed { // Load's bag also holds module-graph errors (cycles), which only gate their modules
		prog.Resolve(bag)
		prog.MarkFailed(bag)
		res = check.ProgramWith(prog, bag, o)
	}
	bag.Sort()
	return prog, res, bag, nil
}

// Sources maps each module's file to its lines, for diag.RenderText.
func Sources(prog *names.Program) map[string][]string {
	sources := map[string][]string{}
	for _, m := range prog.Modules {
		sources[m.File] = m.Lines
	}
	for _, m := range prog.Refused {
		sources[m.File] = m.Lines
	}
	return sources
}

// GoCmd runs the go command with args in the generated module dir.
func GoCmd(dir string, args ...string) ([]byte, error) {
	return GoCmdContext(context.Background(), dir, args...)
}

// GoCmdContext is GoCmd, the go command killed when ctx is done. The go command's work files
// go into a fresh directory (GOTMPDIR, under os.TempDir) that GoCmdContext removes when the
// command returns, however it ends: a killed go cannot remove its own go-build* directory.
func GoCmdContext(ctx context.Context, dir string, args ...string) ([]byte, error) {
	return goCmdEnv(ctx, dir, nil, args...)
}

// goCmdEnv is GoCmdContext with env added to the go command's environment (last, so it wins).
func goCmdEnv(ctx context.Context, dir string, env []string, args ...string) ([]byte, error) {
	tmp, err := os.MkdirTemp("", "alder-go-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tmp)
	cmd := exec.CommandContext(ctx, "go", args...)
	cmd.WaitDelay = 2 * time.Second // a compiler it started may hold the output a moment longer
	cmd.Dir = dir
	cmd.Env = append(append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod", "GOTMPDIR="+tmp), env...)
	return cmd.CombinedOutput()
}

// VetApp vets package pkg of the generated module out (files are the files alder wrote there)
// and returns nil, or an error saying why it does not vet (with go vet's output): Go files
// someone else put in out, or else an internal error. Either is exit code 2 for `alder build`.
// out is build/<app> or a scratch directory (scratch.Compile); the message names it.
func VetApp(out string, files map[string][]byte, pkg string) error {
	vetOut, err := GoCmd(out, "vet", "-mod=mod", pkg)
	if err == nil {
		return nil
	}
	if mine := ForeignGoFiles(out, files); len(mine) > 0 {
		return fmt.Errorf("the Go in %s does not vet, and %s holds Go files alder did not generate: %s; %s must contain only generated files, so move them out and try again: %v\n%s",
			out, out, strings.Join(mine, ", "), out, err, vetOut)
	}
	return fmt.Errorf("internal error: the generated Go in %s (%s) does not vet: %v\n%s", out, strings.Join(slices.Sorted(maps.Keys(files)), ", "), err, vetOut)
}

// IsDir reports whether path is a directory.
func IsDir(path string) bool {
	st, err := os.Stat(path)
	return err == nil && st.IsDir()
}

// CopyStatic replaces dst with a copy of the directory src (nothing when src does not exist),
// then writes the design system's assets into it (WriteDesignSystem): every build serves
// /static/al/al.css, whether or not the app has a static directory of its own.
func CopyStatic(src, dst string) error {
	if err := os.RemoveAll(dst); err != nil {
		return err
	}
	if IsDir(src) {
		if err := os.CopyFS(dst, os.DirFS(src)); err != nil {
			return err
		}
	}
	return WriteDesignSystem(dst)
}

// DesignSystemFiles are the `alder-ui` assets (rt/al/, vendored by scripts/vendor-al.sh) every
// build writes under static/al/: the stylesheet a page links as /static/al/al.css, and the
// Custom Elements Manifest the checker reads (served too, for other tools).
var DesignSystemFiles = []string{"al.css", "custom-elements.json"}

// WriteDesignSystem writes DesignSystemFiles into staticDir/al/ from the embedded runtime. The
// directory is the compiler's: a file of the app's own static/al/ with one of these names is
// replaced.
func WriteDesignSystem(staticDir string) error {
	dir := filepath.Join(staticDir, "al")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for _, name := range DesignSystemFiles {
		b, err := rt.Files.ReadFile("al/" + name)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, name), b, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// WriteGenerated replaces the generated files in dir with files: it deletes go.mod and every Go
// file there (and in dir/caps, the generated caps package, which it removes when it is left
// empty) that starts with the generated-code header, then writes files, a name with a
// directory ("caps/caps__alder.go") into that subdirectory. Other files are kept.
// Gen names its files <Module>_alder.go; matching every *.go by its header also deletes the
// <Module>.go files of builds before that naming (M3a), so an old build/ directory is cleaned up.
func WriteGenerated(dir string, files map[string][]byte) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for _, sub := range []string{".", "caps"} {
		entries, err := os.ReadDir(filepath.Join(dir, sub))
		if err != nil {
			if sub != "." && os.IsNotExist(err) {
				continue
			}
			return err
		}
		for _, e := range entries {
			path := filepath.Join(dir, sub, e.Name())
			if e.IsDir() {
				continue
			}
			stale := sub == "." && e.Name() == "go.mod"
			if !stale && strings.HasSuffix(e.Name(), ".go") {
				if stale, err = isGenerated(path); err != nil {
					return err
				}
			}
			if stale {
				if err := os.Remove(path); err != nil {
					return err
				}
			}
		}
		if sub != "." {
			os.Remove(filepath.Join(dir, sub)) // only when empty
		}
	}
	for name, b := range files {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, b, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// ForeignGoFiles lists the Go files of the package in dir (sorted) that are not among the
// generated files: go vet sees them too, so they can make a correct build fail. (The
// subdirectories adapters/, caps/ and cmd/ hold alder's copies, its wiring and its command.)
func ForeignGoFiles(dir string, files map[string][]byte) []string {
	var out []string
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		if _, ok := files[e.Name()]; !e.IsDir() && strings.HasSuffix(e.Name(), ".go") && !ok {
			out = append(out, e.Name())
		}
	}
	slices.Sort(out)
	return out
}

func isGenerated(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()
	line, err := bufio.NewReader(f).ReadString('\n')
	if err != nil && !errors.Is(err, io.EOF) {
		return false, err
	}
	return strings.HasPrefix(line, GeneratedHeader), nil
}

// RuntimeDir is the directory, inside a generated module, that WriteRuntime writes the runtime's
// module into; the generated go.mod says `replace alder => ./rt`.
const RuntimeDir = "rt"

// WriteRuntime writes the runtime embedded in this binary (rt.Files) into dst/rt/ as the module
// alder that the generated module in dst requires: dist/go.mod.txt and dist/go.sum.txt become
// rt/go.mod and rt/go.sum, the module's root, and every other file keeps its path in the
// repository under it, so the package alder/rt is rt/rt/, alder/rt/html is rt/rt/html/, and so on
// (an import path is the module's name followed by the package's directory in the module). It
// also writes dst/go.sum (the same sums: the app module's dependencies are the runtime's), so
// `go build` needs no network once the module cache holds modernc.org/sqlite.
//
// It refreshes rather than adds: a file under dst/rt/ that the embedded runtime does not have
// (one an older compiler wrote, or anyone else's) is removed, with the directories left empty,
// so the copy is always exactly this compiler's runtime. A file whose content is already right
// is not rewritten.
func WriteRuntime(dst string) error {
	want := map[string][]byte{} // path under dst/rt (slash-separated) → content
	err := fs.WalkDir(rt.Files, ".", func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		b, err := rt.Files.ReadFile(path)
		if err != nil {
			return err
		}
		switch path {
		case "dist/go.mod.txt":
			path = "go.mod"
		case "dist/go.sum.txt":
			path = "go.sum"
		default:
			path = "rt/" + path
		}
		want[path] = b
		return nil
	})
	if err != nil {
		return err
	}
	if want["go.mod"] == nil || want["go.sum"] == nil {
		return errors.New("internal error: the embedded runtime has no go.mod or go.sum")
	}
	root := filepath.Join(dst, RuntimeDir)
	if err := os.MkdirAll(root, 0o755); err != nil {
		return err
	}
	if !IsDir(root) {
		return fmt.Errorf("%s is not a directory", root)
	}
	// remove what the runtime does not have, deepest first so emptied directories go too
	var dirs []string
	err = filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		switch {
		case d.IsDir():
			if rel != "." {
				dirs = append(dirs, path)
			}
		case want[rel] == nil || !d.Type().IsRegular():
			return os.Remove(path)
		}
		return nil
	})
	if err != nil {
		return err
	}
	for _, d := range slices.Backward(dirs) {
		os.Remove(d) // only when empty
	}
	for _, rel := range slices.Sorted(maps.Keys(want)) {
		if err := writeIfChanged(filepath.Join(root, filepath.FromSlash(rel)), want[rel]); err != nil {
			return err
		}
	}
	return writeIfChanged(filepath.Join(dst, "go.sum"), want["go.sum"])
}

// FetchingLine is what a build prints (on standard error) before DownloadDeps downloads the
// runtime's dependencies, which happens once per machine (per Go module cache).
const FetchingLine = "fetching modernc.org/sqlite (first build on this machine)"

// DownloadError is DownloadDeps' error: the runtime's dependencies are not in Go's module cache
// and could not be downloaded. It is the environment's fault (no network, GOPROXY=off, a proxy
// that refuses), not the program's and not the compiler's: the commands exit 1.
type DownloadError struct {
	Proxy string // GOPROXY as the go command sees it
	Out   string // the go command's output
}

func (e *DownloadError) Error() string {
	return fmt.Sprintf("could not download the runtime's dependency modernc.org/sqlite through Go's module proxy (GOPROXY=%s); the first build on a machine needs network access:\n%s",
		e.Proxy, strings.TrimRight(e.Out, "\n"))
}

// DownloadDeps makes sure the modules the runtime requires (the requirements of the go.mod
// WriteRuntime wrote into dir/rt) are in Go's module cache, before go vet or go build in dir
// would fail on them with an error that looks like the compiler's. It first asks with the
// network off (`GOPROXY=off go mod download <modules>`), which succeeds at once on a machine
// that has built an app before; only when that fails does it call fetching (when set) and
// download them through the configured proxy. Its error is a *DownloadError, or ctx's.
func DownloadDeps(ctx context.Context, dir string, fetching func()) error {
	mods, err := runtimeRequires(filepath.Join(dir, RuntimeDir, "go.mod"))
	if err != nil {
		return err
	}
	if len(mods) == 0 {
		return nil
	}
	args := append([]string{"mod", "download"}, mods...)
	if _, err := goCmdEnv(ctx, dir, []string{"GOPROXY=off"}, args...); err == nil {
		return nil
	}
	if ctx.Err() != nil {
		return ctx.Err()
	}
	if fetching != nil {
		fetching()
	}
	out, err := GoCmdContext(ctx, dir, args...)
	if err == nil {
		return nil
	}
	if ctx.Err() != nil {
		return ctx.Err()
	}
	proxy, perr := GoCmdContext(ctx, dir, "env", "GOPROXY")
	if perr != nil {
		proxy = []byte("?")
	}
	return &DownloadError{Proxy: strings.TrimSpace(string(proxy)), Out: string(out)}
}

// runtimeRequires lists the module paths the go.mod at path requires.
func runtimeRequires(path string) ([]string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var mods []string
	inBlock := false
	for _, line := range strings.Split(string(b), "\n") {
		f := strings.Fields(line)
		switch {
		case len(f) == 2 && f[0] == "require" && f[1] == "(":
			inBlock = true
		case len(f) > 0 && f[0] == ")":
			inBlock = false
		case len(f) >= 3 && f[0] == "require":
			mods = append(mods, f[1])
		case inBlock && len(f) >= 2 && !strings.HasPrefix(f[0], "//"):
			mods = append(mods, f[0])
		}
	}
	return mods, nil
}

// writeIfChanged writes b to path (creating its directory) unless path already holds b.
func writeIfChanged(path string, b []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, b) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, b, 0o644)
}
