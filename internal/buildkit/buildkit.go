// Package buildkit holds the pieces of turning an app directory into a Go executable that
// `alder build`, `alder run`, `alder dump` and the scratch-module runner (internal/scratch) share:
// loading and checking the app, writing the generated module, copying the app's adapters and
// static files next to it, and running the go command there.
package buildkit

import (
	"bufio"
	"context"
	"errors"
	"fmt"
	"io"
	"maps"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"slices"
	"strings"
	"time"

	"alder/internal/check"
	"alder/internal/diag"
	"alder/internal/names"
	"alder/internal/syntax"
	"alder/internal/types"
)

// GeneratedHeader starts every Go file gen emits; only such files are ever deleted.
const GeneratedHeader = "// Code generated by alder"

// StdError is the error LoadChecked returns (alone) when the standard library does not load: an
// internal error of the compiler, not an I/O failure of the app.
type StdError struct{ Err error }

func (e *StdError) Error() string { return e.Err.Error() }

// LoadChecked loads the app in dir (every .alder file under dir/app) plus the already parsed
// modules extra (added after the directory's, under the usual duplicate and cycle rules), and,
// unless a file failed to parse, resolves names and type-checks it. The bag holds every
// diagnostic, sorted. res is nil when the program was not checked (a parse error). ioErrs are the
// I/O failures of reading dir (or a single *StdError); with any, the program must not be used.
func LoadChecked(dir string, extra []*syntax.Module) (prog *names.Program, res *check.Result, bag *diag.Bag, ioErrs []error) {
	return LoadCheckedWith(dir, extra, check.Options{})
}

// LoadCheckedWith is LoadChecked with the checker's options (check.ProgramWith).
func LoadCheckedWith(dir string, extra []*syntax.Module, o check.Options) (prog *names.Program, res *check.Result, bag *diag.Bag, ioErrs []error) {
	std, err := types.LoadStd()
	if err != nil {
		return nil, nil, &diag.Bag{}, []error{&StdError{err}}
	}
	prog, bag, ioErrs = names.Load(dir, std, extra...)
	if len(ioErrs) > 0 {
		return prog, nil, bag, ioErrs
	}
	if !prog.ParseFailed { // Load's bag also holds module-graph errors (cycles), which only gate their modules
		prog.Resolve(bag)
		prog.MarkFailed(bag)
		res = check.ProgramWith(prog, bag, o)
	}
	bag.Sort()
	return prog, res, bag, nil
}

// Sources maps each module's file to its lines, for diag.RenderText.
func Sources(prog *names.Program) map[string][]string {
	sources := map[string][]string{}
	for _, m := range prog.Modules {
		sources[m.File] = m.Lines
	}
	for _, m := range prog.Refused {
		sources[m.File] = m.Lines
	}
	return sources
}

// GoCmd runs the go command with args in the generated module dir.
func GoCmd(dir string, args ...string) ([]byte, error) {
	return GoCmdContext(context.Background(), dir, args...)
}

// GoCmdContext is GoCmd, the go command killed when ctx is done. The go command's work files
// go into a fresh directory (GOTMPDIR, under os.TempDir) that GoCmdContext removes when the
// command returns, however it ends: a killed go cannot remove its own go-build* directory.
func GoCmdContext(ctx context.Context, dir string, args ...string) ([]byte, error) {
	tmp, err := os.MkdirTemp("", "alder-go-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tmp)
	cmd := exec.CommandContext(ctx, "go", args...)
	cmd.WaitDelay = 2 * time.Second // a compiler it started may hold the output a moment longer
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod", "GOTMPDIR="+tmp)
	return cmd.CombinedOutput()
}

// VetApp vets package pkg of the generated module out (files are the files alder wrote there)
// and returns nil, or an error saying why it does not vet (with go vet's output): Go files
// someone else put in out, or else an internal error. Either is exit code 2 for `alder build`.
// out is build/<app> or a scratch directory (scratch.Compile); the message names it.
func VetApp(out string, files map[string][]byte, pkg string) error {
	vetOut, err := GoCmd(out, "vet", "-mod=mod", pkg)
	if err == nil {
		return nil
	}
	if mine := ForeignGoFiles(out, files); len(mine) > 0 {
		return fmt.Errorf("the Go in %s does not vet, and %s holds Go files alder did not generate: %s; %s must contain only generated files, so move them out and try again: %v\n%s",
			out, out, strings.Join(mine, ", "), out, err, vetOut)
	}
	return fmt.Errorf("internal error: the generated Go in %s (%s) does not vet: %v\n%s", out, strings.Join(slices.Sorted(maps.Keys(files)), ", "), err, vetOut)
}

// IsDir reports whether path is a directory.
func IsDir(path string) bool {
	st, err := os.Stat(path)
	return err == nil && st.IsDir()
}

// CopyStatic replaces dst with a copy of the directory src, or removes it when src does not
// exist.
func CopyStatic(src, dst string) error {
	if err := os.RemoveAll(dst); err != nil {
		return err
	}
	if !IsDir(src) {
		return nil
	}
	return os.CopyFS(dst, os.DirFS(src))
}

// WriteGenerated replaces the generated files in dir with files: it deletes go.mod and every Go
// file there (and in dir/caps, the generated caps package, which it removes when it is left
// empty) that starts with the generated-code header, then writes files, a name with a
// directory ("caps/caps__alder.go") into that subdirectory. Other files are kept.
// Gen names its files <Module>_alder.go; matching every *.go by its header also deletes the
// <Module>.go files of builds before that naming (M3a), so an old build/ directory is cleaned up.
func WriteGenerated(dir string, files map[string][]byte) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for _, sub := range []string{".", "caps"} {
		entries, err := os.ReadDir(filepath.Join(dir, sub))
		if err != nil {
			if sub != "." && os.IsNotExist(err) {
				continue
			}
			return err
		}
		for _, e := range entries {
			path := filepath.Join(dir, sub, e.Name())
			if e.IsDir() {
				continue
			}
			stale := sub == "." && e.Name() == "go.mod"
			if !stale && strings.HasSuffix(e.Name(), ".go") {
				if stale, err = isGenerated(path); err != nil {
					return err
				}
			}
			if stale {
				if err := os.Remove(path); err != nil {
					return err
				}
			}
		}
		if sub != "." {
			os.Remove(filepath.Join(dir, sub)) // only when empty
		}
	}
	for name, b := range files {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, b, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// ForeignGoFiles lists the Go files of the package in dir (sorted) that are not among the
// generated files: go vet sees them too, so they can make a correct build fail. (The
// subdirectories adapters/, caps/ and cmd/ hold alder's copies, its wiring and its command.)
func ForeignGoFiles(dir string, files map[string][]byte) []string {
	var out []string
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		if _, ok := files[e.Name()]; !e.IsDir() && strings.HasSuffix(e.Name(), ".go") && !ok {
			out = append(out, e.Name())
		}
	}
	slices.Sort(out)
	return out
}

func isGenerated(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()
	line, err := bufio.NewReader(f).ReadString('\n')
	if err != nil && !errors.Is(err, io.EOF) {
		return false, err
	}
	return strings.HasPrefix(line, GeneratedHeader), nil
}

// RepoRoot is the alder repository the generated go.mod points at (replace alder => …):
// $ALDER_ROOT when set, else the source tree this binary was built from.
func RepoRoot() (string, error) {
	if r := os.Getenv("ALDER_ROOT"); r != "" {
		return filepath.Abs(r)
	}
	_, file, _, ok := runtime.Caller(0)
	if ok {
		root := filepath.Dir(filepath.Dir(filepath.Dir(file))) // internal/buildkit/buildkit.go → repository
		if b, err := os.ReadFile(filepath.Join(root, "go.mod")); err == nil && strings.HasPrefix(string(b), "module alder\n") {
			return root, nil
		}
	}
	return "", errors.New("cannot find the alder repository for the generated go.mod; set ALDER_ROOT")
}
