// Literal printers: a value as the Alder expression that builds it, so a failing property's
// arguments can be pasted into a plain test (spec §6). The generated lit__ functions of a test
// build combine these, one per derived type: brand constructors are spelled out, a Time is
// `Time.fromMillis N` and a Date counts days from the epoch.

// TextLit is s as an Alder string literal: `"`, `\`, `{` (which would start an
// interpolation), newline, carriage return and tab are escaped; every other printable code
// point (unicode.IsPrint) is written as itself, and derived Text is only those (spec §0a).
// Alder has no escape for any other code point (a control, a format character) nor for
// invalid UTF-8, which a Fuzz.forAll generator can make: such a one is written `\u{XXXX}`
// (invalid UTF-8 as U+FFFD), readable but no Alder, so the literal is not Pasteable.
func TextLit(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i, r := range s {
		if r == utf8.RuneError {
			if _, n := utf8.DecodeRuneInString(s[i:]); n == 1 {
				b.WriteString(noLiteral + "FFFD}")
				continue
			}
		}
		if !unicode.IsPrint(r) && r != '\n' && r != '\r' && r != '\t' {
			fmt.Fprintf(&b, "%s%X}", noLiteral, r)
			continue
		}
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '{':
			b.WriteString(`\{`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// noLiteral starts how TextLit writes a code point Alder has no literal for. No Alder literal
// these printers make holds it: in TextLit's output every other `\` is followed by one of
// `"\{nrt`.
const noLiteral = `\u{`

// Pasteable reports whether lit, made by these printers, is Alder source: false when a Text in
// it has a code point Alder cannot write (TextLit).
func Pasteable(lit string) bool { return !strings.Contains(lit, noLiteral) }

// IntLit is n as an Alder Int literal. MinInt64 has none (its magnitude is no Int), so it is
// the expression `(-9223372036854775807 - 1)`.
func IntLit(n int64) string {
	if n == math.MinInt64 {
		return "(-9223372036854775807 - 1)"
	}
	return strconv.FormatInt(n, 10)
}

// FloatLit is f as an Alder Float literal: digits, '.', digits, never an exponent (the lexer
// reads exponents, but the plain decimal form is the one generated), the shortest such text
// that reads back as f. Negative zero is -0.0 (the parser and gen keep its sign). Fuzz never
// draws NaN or an infinity, but a Fuzz.forAll generator can make one (`Fuzz.map (\x -> x / 0.0) Fuzz.float`); having no literal, it is the parenthesised
// division that evaluates to it, `(1.0 / 0.0)`, `(-1.0 / 0.0)` or `(0.0 / 0.0)` (Float
// division by zero is infinity or NaN, book chapter 4).
func FloatLit(f float64) string {
	switch {
	case math.IsNaN(f):
		return "(0.0 / 0.0)"
	case math.IsInf(f, 1):
		return "(1.0 / 0.0)"
	case math.IsInf(f, -1):
		return "(-1.0 / 0.0)"
	}
	s := strconv.FormatFloat(f, 'f', -1, 64)
	if !strings.Contains(s, ".") {
		s += ".0"
	}
	return s
}

// BoolLit is True or False.
func BoolLit(b bool) string {
	if b {
		return "True"
	}
	return "False"
}

// TimeLit is the Time ms milliseconds after the epoch: `Time.fromMillis N`.
func TimeLit(ms int64) string { return Apply("Time.fromMillis", IntLit(ms)) }

// DateLit is the Date days after 1970-01-01: `Date.addDays N (Time.toDate Time.epoch)`.
func DateLit(days int) string {
	return Apply("Date.addDays", IntLit(int64(days))) + " (Time.toDate Time.epoch)"
}

// DaysOf is the number of days from 1970-01-01 to d.
func DaysOf(d rt.Date) int {
	return int(d.Time().Sub(time.Unix(0, 0).UTC()).Hours() / 24)
}

// BytesLit is b as `Text.toBytes "…"`: generated Bytes are UTF-8 (Bytes), so the text is
// exact.
func BytesLit(b []byte) string { return Apply("Text.toBytes", TextLit(string(b))) }

// Apply is the application of fn to the literal arg, which is parenthesised unless it is an
// atom: a string, list, record or parenthesised literal, or a single word that is no negative
// number.
func Apply(fn, arg string) string {
	return fn + " " + Atom(arg)
}

// Atom is lit, parenthesised unless it already reads as one argument.
func Atom(lit string) string {
	if lit == "" {
		return "()"
	}
	switch lit[0] {
	case '"', '[', '{', '(':
		return lit
	case '-':
		return "(" + lit + ")"
	}
	if strings.ContainsRune(lit, ' ') {
		return "(" + lit + ")"
	}
	return lit
}

// ListLit is the list literal of xs, each element printed by lit.
func ListLit[A any](xs []A, lit func(A) string) string {
	parts := make([]string, len(xs))
	for i, x := range xs {
		parts[i] = lit(x)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// MaybeLit is Nothing or `Just x`.
func MaybeLit[A any](m rt.Maybe[A], lit func(A) string) string {
	if !m.Ok {
		return "Nothing"
	}
	return Apply("Just", lit(m.Val))
}

// ResultLit is `Ok x` or `Err e`.
func ResultLit[E, A any](r rt.Result[E, A], litE func(E) string, litA func(A) string) string {
	if r.IsOk {
		return Apply("Ok", litA(r.Val))
	}
	return Apply("Err", litE(r.Err))
}

// DictLit is `Dict.empty`, or `Dict.fromList [{ key: k, value: v }, …]` in the dictionary's
// order.
func DictLit[K, V any](d rt.Dict[K, V], litK func(K) string, litV func(V) string) string {
	if d.Len() == 0 {
		return "Dict.empty"
	}
	ks, vs := d.Keys(), d.Values()
	parts := make([]string, len(ks))
	for i := range ks {
		parts[i] = RecordLit([]string{"key", "value"}, []string{litK(ks[i]), litV(vs[i])})
	}
	return "Dict.fromList [" + strings.Join(parts, ", ") + "]"
}

// RecordLit is the record literal of fields names with the printed values vals.
func RecordLit(names, vals []string) string {
	if len(names) == 0 {
		return "{}"
	}
	parts := make([]string, len(names))
	for i, n := range names {
		parts[i] = n + ": " + vals[i]
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

// Quals is how the module a literal is pasted into writes the constructors and brands of each
// module (by path): "" for its own, else the module's canonical qualifier there. A module
// absent from it is written by its path; a nil Quals writes every name bare.
type Quals map[string]string

// Name is the constructor or brand name of module as the module q is for writes it: `Leaf`,
// `Todo.Leaf`.
func (q Quals) Name(module, name string) string {
	if q == nil {
		return name
	}
	qual, ok := q[module]
	switch {
	case !ok:
		return module + "." + name
	case qual == "":
		return name
	}
	return qual + "." + name
}
