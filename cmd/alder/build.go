// generatedHeader starts every Go file gen emits; only such files are ever deleted.
const generatedHeader = "// Code generated by alder"

// runBuildTo is `alder build [--emit] [dir]`: check the app in dir and, when it has no errors
// and no holes, lower it and emit its Go into build/<app>/ (app is dir's base name), the module
// "app". With --emit it stops there, after vetting that package. Without, it builds the app's
// executable build/<app>/<app>: it copies dir/adapters/*.go (the Go implementing the app's
// capabilities, package adapters; only the top-level .go files, and a directory without any
// counts as absent) to build/<app>/adapters/ and dir/static/ to
// build/<app>/static/ (replacing earlier copies), writes the command build/<app>/cmd/main.go,
// vets the module and builds the command.
//
// Exit 0 on success; 1 when the program has errors or holes, when it has capabilities but no
// adapters directory, or when the adapters do not compile (Go's errors are printed as they
// are); 2 for usage errors and internal errors (including generated Go that does not vet).
func runBuildTo(args []string, stdout, stderr io.Writer) int {
	dir, emit, haveDir := ".", false, false
	for _, a := range args {
		switch {
		case a == "--emit":
			emit = true
		case strings.HasPrefix(a, "-") || haveDir:
			usageTo(stderr)
			return 2
		default:
			dir, haveDir = a, true
		}
	}
	path, code := buildTo(dir, emit, stdout, stderr)
	if code == 0 {
		fmt.Fprintf(stdout, "wrote %s\n", path)
	}
	return code
}

// buildApp builds the executable of the app in dir as `alder build dir` does (buildTo), every
// message (diagnostics included) going to stderr, and returns its absolute path with exit code
// 0, or "" with the build's exit code. `alder run` rebuilds with it.
func buildApp(dir string, stderr io.Writer) (binary string, code int) {
	path, code := buildTo(dir, false, stderr, stderr)
	if code != 0 {
		return "", code
	}
	abs, err := filepath.Abs(path)
	if err != nil {
		fmt.Fprintf(stderr, "alder build: %v\n", err)
		return "", 2
	}
	return abs, 0
}

// buildTo is the work of `alder build` after its arguments are parsed: it returns the path it
// wrote (build/<app> with emit, else the executable build/<app>/<app>) and exit code 0, or ""
// and the exit code runBuildTo documents. Error diagnostics go to stdout, everything else to
// stderr.
func buildTo(dir string, emit bool, stdout, stderr io.Writer) (written string, code int) {
	defer func() {
		if r := recover(); r != nil {
			fmt.Fprintf(stderr, "alder build: internal error: %v\n", r)
			written, code = "", 2
		}
	}()
	abs, err := filepath.Abs(dir)
	if err != nil {
		fmt.Fprintf(stderr, "alder build: %v\n", err)
		return "", 2
	}
	repo, err := repoRoot()
	if err != nil {
		fmt.Fprintf(stderr, "alder build: %v\n", err)
		return "", 2
	}

	std, err := types.LoadStd()
	if err != nil {
		fmt.Fprintf(stderr, "alder: internal error loading stdlib: %v\n", err)
		return "", 2
	}
	prog, bag, ioErrs := names.Load(dir, std)
	if len(ioErrs) > 0 {
		for _, e := range ioErrs {
			fmt.Fprintf(stderr, "alder build: %v\n", e)
		}
		return "", 2
	}
	if len(prog.Modules) == 0 {
		fmt.Fprintf(stderr, "alder build: no .alder files under %s/app\n", dir)
		return "", 2
	}
	var res *check.Result
	if !prog.ParseFailed {
		prog.Resolve(bag)
		prog.MarkFailed(bag)
		res = check.Program(prog, bag)
	}
	bag.Sort()
	sources := map[string][]string{}
	for _, m := range prog.Modules {
		sources[m.File] = m.Lines
	}
	for _, d := range bag.Items {
		w := stdout
		if d.Severity == "warning" {
			w = stderr
		}
		fmt.Fprint(w, diag.RenderText(d, sources[d.Span.File]))
	}
	if bag.HasErrors() || res == nil {
		return "", 1
	}
	if res.Holes > 0 {
		fmt.Fprintf(stderr, "alder build: the program has %d typed hole(s); fill them before building\n", res.Holes)
		return "", 1
	}

	p := ir.Lower(prog, res)
	name := filepath.Base(abs)
	adapters := filepath.Join(dir, "adapters")
	hasAdapters := hasGoFiles(adapters) // an empty adapters/ (or one of notes only) is none
	if !emit && !hasAdapters && len(p.Caps) > 0 {
		var list []string
		for _, c := range p.Caps {
			list = append(list, fmt.Sprintf("%s.%s (interface app.Cap__%s__%s)", c.Module, c.Name, strings.ReplaceAll(c.Module, ".", "__"), c.Name))
		}
		fmt.Fprintf(stderr, "%s needs an adapters package: create adapters/caps.go with `func Caps() app.Caps` implementing: %s\n", dir, strings.Join(list, ", "))
		return "", 1
	}
	files, err := gen.Emit(p, gen.Options{RepoPath: repo})
	if err != nil {
		fmt.Fprintf(stderr, "alder build: internal error: %v\n", err)
		return "", 2
	}
	out := filepath.Join("build", name)
	if err := writeGenerated(out, files); err != nil {
		fmt.Fprintf(stderr, "alder build: %v\n", err)
		return "", 2
	}
	if emit {
		// the app package alone: a cmd/ or adapters/ of an earlier full build is not vetted
		if code := vetApp(out, files, ".", stderr); code != 0 {
			return "", code
		}
		return out, 0
	}

	// the executable
	if err := copyAdapters(adapters, filepath.Join(out, "adapters"), hasAdapters); err != nil {
		fmt.Fprintf(stderr, "alder build: %v\n", err)
		return "", 2
	}
	if err := copyStatic(filepath.Join(dir, "static"), filepath.Join(out, "static")); err != nil {
		fmt.Fprintf(stderr, "alder build: %v\n", err)
		return "", 2
	}
	if err := os.MkdirAll(filepath.Join(out, "cmd"), 0o755); err != nil {
		fmt.Fprintf(stderr, "alder build: %v\n", err)
		return "", 2
	}
	if err := os.WriteFile(filepath.Join(out, "cmd", "main.go"), gen.Main(name, hasAdapters), 0o644); err != nil {
		fmt.Fprintf(stderr, "alder build: %v\n", err)
		return "", 2
	}
	if vetOut, err := goCmd(out, "vet", "-mod=mod", "./..."); err != nil {
		// the generated package first: when it does not vet, that is not the adapters' fault
		if code := vetApp(out, files, ".", stderr); code != 0 {
			return "", code
		}
		if hasAdapters {
			fmt.Fprintf(stderr, "alder build: the adapters package (%s, copied to %s) does not compile with the app: %v\n%s",
				adapters, filepath.Join(out, "adapters"), err, vetOut)
			if strings.Contains(string(vetOut), "adapters.Caps") {
				fmt.Fprintf(stderr, "the adapters package must declare `func Caps() app.Caps`\n")
			}
			return "", 1
		}
		fmt.Fprintf(stderr, "alder build: internal error: the generated Go in %s does not vet: %v\n%s", out, err, vetOut)
		return "", 2
	}
	if buildOut, err := goCmd(out, "build", "-mod=mod", "-o", name, "./cmd"); err != nil {
		fmt.Fprintf(stderr, "alder build: internal error: go build of %s failed: %v\n%s", out, err, buildOut)
		return "", 2
	}
	return filepath.Join(out, name), 0
}

// goCmd runs the go command with args in the generated module dir.
func goCmd(dir string, args ...string) ([]byte, error) {
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod")
	return cmd.CombinedOutput()
}

// vetApp vets package pkg of the generated module out (files are the files alder wrote there)
// and returns 0, or reports why it does not vet and returns 2: Go files someone else put in
// out, or else an internal error.
func vetApp(out string, files map[string][]byte, pkg string, stderr io.Writer) int {
	vetOut, err := goCmd(out, "vet", "-mod=mod", pkg)
	if err == nil {
		return 0
	}
	if mine := foreignGoFiles(out, files); len(mine) > 0 {
		fmt.Fprintf(stderr, "alder build: the Go in %s does not vet, and %s holds Go files alder did not generate: %s; build/<app> must contain only generated files, so move them out and build again: %v\n%s",
			out, out, strings.Join(mine, ", "), err, vetOut)
		return 2
	}
	fmt.Fprintf(stderr, "alder build: internal error: the generated Go in %s (%s) does not vet: %v\n%s", out, strings.Join(slices.Sorted(maps.Keys(files)), ", "), err, vetOut)
	return 2
}

// hasGoFiles reports whether the directory dir holds a .go file at its top level (the files
// copyAdapters copies).
func hasGoFiles(dir string) bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".go") {
			return true
		}
	}
	return false
}

// isDir reports whether path is a directory.
func isDir(path string) bool {
	st, err := os.Stat(path)
	return err == nil && st.IsDir()
}

// copyAdapters replaces the Go files of dst with those of src (when present). Every Go file in
// dst is a copy alder made, so a file deleted from src disappears from dst too.
func copyAdapters(src, dst string, present bool) error {
	entries, err := os.ReadDir(dst)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".go") {
			if err := os.Remove(filepath.Join(dst, e.Name())); err != nil {
				return err
			}
		}
	}
	if !present {
		os.Remove(dst) // only when empty
		return nil
	}
	if entries, err = os.ReadDir(src); err != nil {
		return err
	}
	if err := os.MkdirAll(dst, 0o755); err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		b, err := os.ReadFile(filepath.Join(src, e.Name()))
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dst, e.Name()), b, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// copyStatic replaces dst with a copy of the directory src, or removes it when src does not
// exist.
func copyStatic(src, dst string) error {
	if err := os.RemoveAll(dst); err != nil {
		return err
	}
	if !isDir(src) {
		return nil
	}
	return os.CopyFS(dst, os.DirFS(src))
}

// writeGenerated replaces the generated files in dir with files: it deletes go.mod and every Go
// file there that starts with the generated-code header, then writes files. Other files are kept.
// Gen names its files <Module>_alder.go; matching every *.go by its header also deletes the
// <Module>.go files of builds before that naming (M3a), so an old build/ directory is cleaned up.
func writeGenerated(dir string, files map[string][]byte) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		path := filepath.Join(dir, e.Name())
		if e.IsDir() {
			continue
		}
		stale := e.Name() == "go.mod"
		if !stale && strings.HasSuffix(e.Name(), ".go") {
			if stale, err = isGenerated(path); err != nil {
				return err
			}
		}
		if stale {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	for name, b := range files {
		if err := os.WriteFile(filepath.Join(dir, name), b, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// foreignGoFiles lists the Go files of the package in dir (sorted) that are not among the
// generated files: go vet sees them too, so they can make a correct build fail. (The
// subdirectories adapters/ and cmd/ hold alder's copies and its command.)
func foreignGoFiles(dir string, files map[string][]byte) []string {
	var out []string
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		if _, ok := files[e.Name()]; !e.IsDir() && strings.HasSuffix(e.Name(), ".go") && !ok {
			out = append(out, e.Name())
		}
	}
	slices.Sort(out)
	return out
}

func isGenerated(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()
	line, err := bufio.NewReader(f).ReadString('\n')
	if err != nil && !errors.Is(err, io.EOF) {
		return false, err
	}
	return strings.HasPrefix(line, generatedHeader), nil
}

// repoRoot is the alder repository the generated go.mod points at (replace alder => …): $ALDER_ROOT
// when set, else the source tree this binary was built from.
func repoRoot() (string, error) {
	if r := os.Getenv("ALDER_ROOT"); r != "" {
		return filepath.Abs(r)
	}
	_, file, _, ok := runtime.Caller(0)
	if ok {
		root := filepath.Dir(filepath.Dir(filepath.Dir(file))) // cmd/alder/build.go → repository
		if b, err := os.ReadFile(filepath.Join(root, "go.mod")); err == nil && strings.HasPrefix(string(b), "module alder\n") {
			return root, nil
		}
	}
	return "", errors.New("cannot find the alder repository for the generated go.mod; set ALDER_ROOT")
}
