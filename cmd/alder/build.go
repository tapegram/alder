// generatedHeader starts every Go file gen emits; only such files are ever deleted.
const generatedHeader = "// Code generated by alder"

// runBuildTo is `alder build --emit [dir]`: check the app in dir and, when it has no errors and
// no holes, lower it, emit its Go into build/<app>/ (app is dir's base name) and vet that
// package. Exit 0 on success, 1 when the program has errors or holes, 2 for usage errors and
// internal errors (including generated Go that does not vet).
func runBuildTo(args []string, stdout, stderr io.Writer) (code int) {
	defer func() {
		if r := recover(); r != nil {
			fmt.Fprintf(stderr, "alder build: internal error: %v\n", r)
			code = 2
		}
	}()
	dir, emit, haveDir := ".", false, false
	for _, a := range args {
		switch {
		case a == "--emit":
			emit = true
		case strings.HasPrefix(a, "-") || haveDir:
			usageTo(stderr)
			return 2
		default:
			dir, haveDir = a, true
		}
	}
	if !emit {
		fmt.Fprintln(stderr, "`alder build` without --emit arrives in M3c")
		return 2
	}
	abs, err := filepath.Abs(dir)
	if err != nil {
		fmt.Fprintf(stderr, "alder build: %v\n", err)
		return 2
	}
	repo, err := repoRoot()
	if err != nil {
		fmt.Fprintf(stderr, "alder build: %v\n", err)
		return 2
	}

	std, err := types.LoadStd()
	if err != nil {
		fmt.Fprintf(stderr, "alder: internal error loading stdlib: %v\n", err)
		return 2
	}
	prog, bag, ioErrs := names.Load(dir, std)
	if len(ioErrs) > 0 {
		for _, e := range ioErrs {
			fmt.Fprintf(stderr, "alder build: %v\n", e)
		}
		return 2
	}
	if len(prog.Modules) == 0 {
		fmt.Fprintf(stderr, "alder build: no .alder files under %s/app\n", dir)
		return 2
	}
	var res *check.Result
	if !prog.ParseFailed {
		prog.Resolve(bag)
		prog.MarkFailed(bag)
		res = check.Program(prog, bag)
	}
	bag.Sort()
	sources := map[string][]string{}
	for _, m := range prog.Modules {
		sources[m.File] = m.Lines
	}
	for _, d := range bag.Items {
		w := stdout
		if d.Severity == "warning" {
			w = stderr
		}
		fmt.Fprint(w, diag.RenderText(d, sources[d.Span.File]))
	}
	if bag.HasErrors() || res == nil {
		return 1
	}
	if res.Holes > 0 {
		fmt.Fprintf(stderr, "alder build: the program has %d typed hole(s); fill them before building\n", res.Holes)
		return 1
	}

	files, err := gen.Emit(ir.Lower(prog, res), gen.Options{RepoPath: repo})
	if err != nil {
		fmt.Fprintf(stderr, "alder build: internal error: %v\n", err)
		return 2
	}
	out := filepath.Join("build", filepath.Base(abs))
	if err := writeGenerated(out, files); err != nil {
		fmt.Fprintf(stderr, "alder build: %v\n", err)
		return 2
	}
	cmd := exec.Command("go", "vet", "-mod=mod", "./...")
	cmd.Dir = out
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod")
	if vetOut, err := cmd.CombinedOutput(); err != nil {
		if mine := foreignGoFiles(out, files); len(mine) > 0 {
			fmt.Fprintf(stderr, "alder build: the Go in %s does not vet, and %s holds Go files alder did not generate: %s; build/<app> must contain only generated files, so move them out and build again: %v\n%s",
				out, out, strings.Join(mine, ", "), err, vetOut)
			return 2
		}
		fmt.Fprintf(stderr, "alder build: internal error: the generated Go in %s (%s) does not vet: %v\n%s", out, strings.Join(slices.Sorted(maps.Keys(files)), ", "), err, vetOut)
		return 2
	}
	fmt.Fprintf(stdout, "wrote %s\n", out)
	return 0
}

// writeGenerated replaces the generated files in dir with files: it deletes go.mod and every Go
// file there that starts with the generated-code header, then writes files. Other files are kept.
// Gen names its files <Module>_alder.go; matching every *.go by its header also deletes the
// <Module>.go files of builds before that naming (M3a), so an old build/ directory is cleaned up.
func writeGenerated(dir string, files map[string][]byte) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		path := filepath.Join(dir, e.Name())
		if e.IsDir() {
			continue
		}
		stale := e.Name() == "go.mod"
		if !stale && strings.HasSuffix(e.Name(), ".go") {
			if stale, err = isGenerated(path); err != nil {
				return err
			}
		}
		if stale {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	for name, b := range files {
		if err := os.WriteFile(filepath.Join(dir, name), b, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// foreignGoFiles lists the Go files under dir (relative to it, sorted) that are not among the
// generated files: go vet ./... sees them too, so they can make a correct build fail.
func foreignGoFiles(dir string, files map[string][]byte) []string {
	var out []string
	filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") {
			return nil
		}
		rel, _ := filepath.Rel(dir, path)
		if _, ok := files[filepath.ToSlash(rel)]; !ok {
			out = append(out, filepath.ToSlash(rel))
		}
		return nil
	})
	slices.Sort(out)
	return out
}

func isGenerated(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()
	line, err := bufio.NewReader(f).ReadString('\n')
	if err != nil && !errors.Is(err, io.EOF) {
		return false, err
	}
	return strings.HasPrefix(line, generatedHeader), nil
}

// repoRoot is the alder repository the generated go.mod points at (replace alder => …): $ALDER_ROOT
// when set, else the source tree this binary was built from.
func repoRoot() (string, error) {
	if r := os.Getenv("ALDER_ROOT"); r != "" {
		return filepath.Abs(r)
	}
	_, file, _, ok := runtime.Caller(0)
	if ok {
		root := filepath.Dir(filepath.Dir(filepath.Dir(file))) // cmd/alder/build.go → repository
		if b, err := os.ReadFile(filepath.Join(root, "go.mod")); err == nil && strings.HasPrefix(string(b), "module alder\n") {
			return root, nil
		}
	}
	return "", errors.New("cannot find the alder repository for the generated go.mod; set ALDER_ROOT")
}
