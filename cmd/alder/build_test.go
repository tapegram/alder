func runBuild(t *testing.T, args ...string) (int, string, string) {
	t.Helper()
	var out, errb bytes.Buffer
	code := runBuildTo(args, &out, &errb)
	return code, out.String(), errb.String()
}

// copyDir copies the tree at src to dst.
func copyDir(t *testing.T, src, dst string) {
	t.Helper()
	if err := os.CopyFS(dst, os.DirFS(src)); err != nil {
		t.Fatal(err)
	}
}

func TestBuildEmit_Todos(t *testing.T) {
	src, err := filepath.Abs("../../examples/todos")
	if err != nil {
		t.Fatal(err)
	}
	tmp := t.TempDir()
	copyDir(t, src, filepath.Join(tmp, "todos"))
	t.Chdir(tmp)
	// stale generated files (one from a module since removed, one an M3a build named
	// <Module>.go) and hand-written ones in the output directory
	out := filepath.Join("build", "todos")
	if err := os.MkdirAll(out, 0o755); err != nil {
		t.Fatal(err)
	}
	const header = "// Code generated by alder; DO NOT EDIT.\n\npackage app\n"
	os.WriteFile(filepath.Join(out, "Gone_alder.go"), []byte(header), 0o644)
	os.WriteFile(filepath.Join(out, "Todos__Index.go"), []byte(header+"\nvar Todos__Index__view = 1\n"), 0o644)
	os.WriteFile(filepath.Join(out, "notes.txt"), []byte("mine"), 0o644)
	os.WriteFile(filepath.Join(out, "mine.go"), []byte("package app\n"), 0o644)

	code, stdout, stderr := runBuild(t, "--emit", "todos")
	if code != 0 {
		t.Fatalf("exit %d\nstdout: %s\nstderr: %s", code, stdout, stderr)
	}
	b, err := os.ReadFile(filepath.Join(out, "Todos__Index_alder.go"))
	if err != nil {
		t.Fatal(err)
	}
	src2 := string(b)
	if !strings.Contains(src2, "func Todos__Index__view(") {
		t.Errorf("Todos__Index_alder.go lacks the view:\n%s", src2)
	}
	for _, want := range []string{"func Todos__Index__load(", "func Todos__Index__update("} {
		if !strings.Contains(src2, want) {
			t.Errorf("Todos__Index_alder.go lacks %s", want)
		}
	}
	if b, err := os.ReadFile(filepath.Join(out, "App_alder.go")); err != nil || !strings.Contains(string(b), "func App__update(") {
		t.Errorf("App_alder.go lacks App__update (%v)", err)
	}
	if b, err := os.ReadFile(filepath.Join(out, "app__alder.go")); err != nil || !strings.Contains(string(b), "var Tables = []db.TableDesc{table__User__User.Desc(), table__Todo__Todo.Desc()}") {
		t.Errorf("app__alder.go: %v\n%s", err, b)
	}
	if b, err := os.ReadFile(filepath.Join(out, "app__alder.go")); err != nil || !strings.Contains(string(b), `var Capabilities = []string{"Auth.Login.Password"}`) {
		t.Errorf("app__alder.go lacks Capabilities: %v\n%s", err, b)
	}
	for _, stale := range []string{"Gone_alder.go", "Todos__Index.go"} {
		if _, err := os.Stat(filepath.Join(out, stale)); !os.IsNotExist(err) {
			t.Errorf("stale generated %s not deleted: %v", stale, err)
		}
	}
	for _, mine := range []string{"notes.txt", "mine.go"} {
		if _, err := os.Stat(filepath.Join(out, mine)); err != nil {
			t.Errorf("hand-written %s deleted: %v", mine, err)
		}
	}
	if _, err := os.Stat(filepath.Join(out, "go.mod")); err != nil {
		t.Errorf("no go.mod: %v", err)
	}
}

// A Go file of the user's in build/<app> that does not vet is named as the cause, not reported
// as an internal error of the compiler (M8).
func TestBuildEmit_ForeignFileDoesNotVet(t *testing.T) {
	src, err := filepath.Abs("../../examples/todos")
	if err != nil {
		t.Fatal(err)
	}
	tmp := t.TempDir()
	copyDir(t, src, filepath.Join(tmp, "todos"))
	t.Chdir(tmp)
	out := filepath.Join("build", "todos")
	if err := os.MkdirAll(out, 0o755); err != nil {
		t.Fatal(err)
	}
	os.WriteFile(filepath.Join(out, "stale_test.go"), []byte("package app\n\nvar _ = Gone__value\n"), 0o644)
	code, stdout, stderr := runBuild(t, "--emit", "todos")
	if code != 2 || strings.Contains(stderr, "internal error") ||
		!strings.Contains(stderr, "holds Go files alder did not generate: stale_test.go; ") || !strings.Contains(stderr, "must contain only generated files") {
		t.Fatalf("exit %d\nstdout: %s\nstderr: %s", code, stdout, stderr)
	}
}

// `alder build` (no --emit) builds the app's executable: the generated package, the app's
// adapters package and static files copied next to it, and the generated command.
func TestBuild_Todos(t *testing.T) {
	src, err := filepath.Abs("../../examples/todos")
	if err != nil {
		t.Fatal(err)
	}
	tmp := t.TempDir()
	copyDir(t, src, filepath.Join(tmp, "todos"))
	t.Chdir(tmp)
	out := filepath.Join("build", "todos")
	// a stale copy of an adapter since deleted, and a stale static file
	os.MkdirAll(filepath.Join(out, "adapters"), 0o755)
	os.WriteFile(filepath.Join(out, "adapters", "gone.go"), []byte("package adapters\n\nvar _ = undefined\n"), 0o644)
	os.MkdirAll(filepath.Join(out, "static"), 0o755)
	os.WriteFile(filepath.Join(out, "static", "gone.css"), []byte("x"), 0o644)

	code, stdout, stderr := runBuild(t, "todos")
	if code != 0 {
		t.Fatalf("exit %d\nstdout: %s\nstderr: %s", code, stdout, stderr)
	}
	if stdout != "wrote build/todos/todos\n" {
		t.Errorf("stdout = %q", stdout)
	}
	st, err := os.Stat(filepath.Join(out, "todos"))
	if err != nil || st.Mode()&0o111 == 0 {
		t.Fatalf("no executable build/todos/todos: %v", err)
	}
	for _, f := range []string{"adapters/password.go", "static/app.css", "cmd/main.go", "routes__alder.go"} {
		if _, err := os.Stat(filepath.Join(out, f)); err != nil {
			t.Errorf("build/todos/%s: %v", f, err)
		}
	}
	for _, f := range []string{"adapters/gone.go", "static/gone.css"} {
		if _, err := os.Stat(filepath.Join(out, f)); !os.IsNotExist(err) {
			t.Errorf("stale build/todos/%s kept: %v", f, err)
		}
	}
	if b, _ := os.ReadFile(filepath.Join(out, "cmd", "main.go")); !strings.Contains(string(b), "app.Serve(adapters.Caps(), app.Options{") {
		t.Errorf("cmd/main.go:\n%s", b)
	}

	// adapters that do not compile are the app's error, shown as Go reports it
	os.WriteFile(filepath.Join("todos", "adapters", "broken.go"), []byte("package adapters\n\nvar _ int = \"x\"\n"), 0o644)
	code, stdout, stderr = runBuild(t, "todos")
	if code != 1 || strings.Contains(stderr, "internal error") || !strings.Contains(stderr, "adapters/broken.go:3:") ||
		!strings.Contains(stderr, "the adapters package (todos/adapters, copied to build/todos/adapters) does not compile") {
		t.Fatalf("broken adapters: exit %d\nstdout: %s\nstderr: %s", code, stdout, stderr)
	}
	// adapters without Caps
	os.Remove(filepath.Join("todos", "adapters", "broken.go"))
	b, _ := os.ReadFile(filepath.Join("todos", "adapters", "password.go"))
	os.WriteFile(filepath.Join("todos", "adapters", "password.go"), []byte(strings.Replace(string(b), "func Caps()", "func caps()", 1)), 0o644)
	code, _, stderr = runBuild(t, "todos")
	if code != 1 || !strings.Contains(stderr, "the adapters package must declare `func Caps() app.Caps`") {
		t.Fatalf("adapters without Caps: exit %d\nstderr: %s", code, stderr)
	}

	// an app with capabilities needs an adapters package; a directory without Go files (only
	// subdirectories, notes) is none
	want := "todos needs an adapters package: create adapters/caps.go with `func Caps() app.Caps` implementing: Auth.Login.Password (interface app.Cap__Auth__Login__Password)\n"
	os.RemoveAll(filepath.Join("todos", "adapters"))
	os.MkdirAll(filepath.Join("todos", "adapters", "sub"), 0o755)
	os.WriteFile(filepath.Join("todos", "adapters", "sub", "x.go"), []byte("package sub\n"), 0o644)
	os.WriteFile(filepath.Join("todos", "adapters", "README"), []byte("todo\n"), 0o644)
	code, stdout, stderr = runBuild(t, "todos")
	if code != 1 || stderr != want {
		t.Fatalf("adapters without Go files: exit %d\nstdout: %s\nstderr: %q\nwant %q", code, stdout, stderr, want)
	}
	os.RemoveAll(filepath.Join("todos", "adapters"))
	code, stdout, stderr = runBuild(t, "todos")
	if code != 1 || stderr != want {
		t.Fatalf("no adapters: exit %d\nstdout: %s\nstderr: %q\nwant %q", code, stdout, stderr, want)
	}
}

func TestBuildEmit_RefusesErrorsAndHoles(t *testing.T) {
	for name, src := range map[string]string{
		"error": "module X\n\nx : Int\nx = \"s\"\n",
		"hole":  "module X\n\nx : Int\nx = ?todo\n",
	} {
		t.Run(name, func(t *testing.T) {
			tmp := t.TempDir()
			os.MkdirAll(filepath.Join(tmp, "app"), 0o755)
			os.WriteFile(filepath.Join(tmp, "app", "X.alder"), []byte(src), 0o644)
			t.Chdir(tmp)
			code, stdout, stderr := runBuild(t, "--emit", ".")
			if code != 1 {
				t.Fatalf("exit %d\nstdout: %s\nstderr: %s", code, stdout, stderr)
			}
			if stdout+stderr == "" {
				t.Error("no diagnostics printed")
			}
			if _, err := os.Stat("build"); !os.IsNotExist(err) {
				t.Errorf("build directory written despite %s", name)
			}
		})
	}
}

// buildTo with an explicit output directory writes there, not to build/<app>.
func TestBuildTo_OutDir(t *testing.T) {
	src, err := filepath.Abs("../../examples/todos")
	if err != nil {
		t.Fatal(err)
	}
	tmp := t.TempDir()
	copyDir(t, src, filepath.Join(tmp, "todos"))
	t.Chdir(tmp)
	var stdout, stderr bytes.Buffer
	out := filepath.Join("elsewhere", "todos")
	path, code := buildTo("todos", false, out, &stdout, &stderr)
	if code != 0 || path != filepath.Join(out, "todos") {
		t.Fatalf("exit %d path %q\nstdout: %s\nstderr: %s", code, path, stdout.String(), stderr.String())
	}
	for _, f := range []string{"todos", "cmd/main.go", "App_alder.go", "adapters/password.go", "static/app.css"} {
		if _, err := os.Stat(filepath.Join(out, f)); err != nil {
			t.Errorf("%s: %v", f, err)
		}
	}
	if _, err := os.Stat("build"); !os.IsNotExist(err) {
		t.Errorf("build/ written: %v", err)
	}
}
