package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func runBuild(t *testing.T, args ...string) (int, string, string) {
	t.Helper()
	var out, errb bytes.Buffer
	code := runBuildTo(args, &out, &errb)
	return code, out.String(), errb.String()
}

// copyDir copies the tree at src to dst.
func copyDir(t *testing.T, src, dst string) {
	t.Helper()
	if err := os.CopyFS(dst, os.DirFS(src)); err != nil {
		t.Fatal(err)
	}
}

func TestBuildEmit_Todos(t *testing.T) {
	src, err := filepath.Abs("../../examples/todos")
	if err != nil {
		t.Fatal(err)
	}
	tmp := t.TempDir()
	copyDir(t, src, filepath.Join(tmp, "todos"))
	t.Chdir(tmp)
	// stale generated files (one from a module since removed, one an M3a build named
	// <Module>.go) and hand-written ones in the output directory
	out := filepath.Join("build", "todos")
	if err := os.MkdirAll(out, 0o755); err != nil {
		t.Fatal(err)
	}
	const header = "// Code generated by alder; DO NOT EDIT.\n\npackage app\n"
	os.WriteFile(filepath.Join(out, "Gone_alder.go"), []byte(header), 0o644)
	os.WriteFile(filepath.Join(out, "Todos__Index.go"), []byte(header+"\nvar Todos__Index__view = 1\n"), 0o644)
	os.WriteFile(filepath.Join(out, "notes.txt"), []byte("mine"), 0o644)
	os.WriteFile(filepath.Join(out, "mine.go"), []byte("package app\n"), 0o644)

	code, stdout, stderr := runBuild(t, "--emit", "todos")
	if code != 0 {
		t.Fatalf("exit %d\nstdout: %s\nstderr: %s", code, stdout, stderr)
	}
	b, err := os.ReadFile(filepath.Join(out, "Todos__Index_alder.go"))
	if err != nil {
		t.Fatal(err)
	}
	src2 := string(b)
	if !strings.Contains(src2, "func Todos__Index__view(") {
		t.Errorf("Todos__Index_alder.go lacks the view:\n%s", src2)
	}
	for _, want := range []string{"func Todos__Index__load(", "func Todos__Index__update("} {
		if !strings.Contains(src2, want) {
			t.Errorf("Todos__Index_alder.go lacks %s", want)
		}
	}
	if b, err := os.ReadFile(filepath.Join(out, "App_alder.go")); err != nil || !strings.Contains(string(b), "func App__update(") {
		t.Errorf("App_alder.go lacks App__update (%v)", err)
	}
	if b, err := os.ReadFile(filepath.Join(out, "tables_alder.go")); err != nil || !strings.Contains(string(b), "var Tables = []db.TableDesc{table__User__User.Desc(), table__Todo__Todo.Desc()}") {
		t.Errorf("tables_alder.go: %v\n%s", err, b)
	}
	for _, stale := range []string{"Gone_alder.go", "Todos__Index.go"} {
		if _, err := os.Stat(filepath.Join(out, stale)); !os.IsNotExist(err) {
			t.Errorf("stale generated %s not deleted: %v", stale, err)
		}
	}
	for _, mine := range []string{"notes.txt", "mine.go"} {
		if _, err := os.Stat(filepath.Join(out, mine)); err != nil {
			t.Errorf("hand-written %s deleted: %v", mine, err)
		}
	}
	if _, err := os.Stat(filepath.Join(out, "go.mod")); err != nil {
		t.Errorf("no go.mod: %v", err)
	}
}

func TestBuild_WithoutEmit(t *testing.T) {
	code, _, stderr := runBuild(t, "../../examples/todos")
	if code != 2 || !strings.Contains(stderr, "alder build` without --emit arrives in M3c") {
		t.Fatalf("exit %d, stderr: %s", code, stderr)
	}
}

func TestBuildEmit_RefusesErrorsAndHoles(t *testing.T) {
	for name, src := range map[string]string{
		"error": "module X\n\nx : Int\nx = \"s\"\n",
		"hole":  "module X\n\nx : Int\nx = ?todo\n",
	} {
		t.Run(name, func(t *testing.T) {
			tmp := t.TempDir()
			os.MkdirAll(filepath.Join(tmp, "app"), 0o755)
			os.WriteFile(filepath.Join(tmp, "app", "X.alder"), []byte(src), 0o644)
			t.Chdir(tmp)
			code, stdout, stderr := runBuild(t, "--emit", ".")
			if code != 1 {
				t.Fatalf("exit %d\nstdout: %s\nstderr: %s", code, stdout, stderr)
			}
			if stdout+stderr == "" {
				t.Error("no diagnostics printed")
			}
			if _, err := os.Stat("build"); !os.IsNotExist(err) {
				t.Errorf("build directory written despite %s", name)
			}
		})
	}
}
