#!/usr/bin/env python3
"""Writes hidden-failures.md: one row per failed hidden test, read from the summaries.
The evidence column is generated (the FAIL block's left/right or reason); the class and the note
are hand-assigned after reading the FAIL block and the model's program (CLASSES below, *hand-scored*).
Usage: python3 experiments/e8-hidden/logs/hidden_failures.py > experiments/e8-hidden/hidden-failures.md"""
import json, pathlib, sys
E = pathlib.Path(__file__).resolve().parent.parent
STALE = "a line posted from a stale page of an order paid meanwhile is refused"
# (task, test name) -> (class, note); a cell-specific key (cond, model, task, sample, name) wins.
CLASSES = {
    ("t6-orders", STALE): ("other",
        "refused with `Reject \"…\"` after checking the current order (re-read in `update`, or the model `load` rebuilt for the request); no line stored. The re-rendered Paid page "
        "has no add-line form, so the text has nowhere to show and the answer is `Rerendered` (probe, findings §2), "
        "which the test does not accept (only `PageMissing`/`RequestFailed`): the test is stricter than the task text"),
}
CELL = {}

def rows():
    for cond in ("with", "without"):
        for p in sorted((E / cond / "runs").glob("*/*/summary.json")):
            s = json.loads(p.read_text())
            h = s.get("hidden") or {}
            for r in h.get("results", []):
                if r.get("ok"):
                    continue
                sample = s["harness"].get("sample", "")
                key = (cond, s["model"], s["task"], sample, r["name"])
                cls, note = CELL.get(key) or CLASSES.get((s["task"], r["name"]), ("UNCLASSIFIED", ""))
                ev = r.get("reason") or f"left `{r.get('left')}` ≠ right `{r.get('right')}`"
                yield cond, s["model"], s["task"], sample, r["name"], cls, ev, note

out = ["# E8 hidden failures", "",
       "Generated by `python3 experiments/e8-hidden/logs/hidden_failures.py` from the summaries. "
       "Every failed hidden test is one row. **Class** and **Reading** are *hand-scored* (the `CLASSES` table in the script, "
       "assigned after reading the FAIL block and the model's program); **Evidence** is the FAIL block as recorded.",
       "", "Classes: `authorization`, `rendering`, `redirect`, `session`, `schema`, `naming`, `other`.", "",
       "| Condition | Model | Task | Sample | Test | Class | Evidence | Reading |", "|---|---|---|---|---|---|---|---|"]
n = 0; counts = {}
for cond, model, task, sample, name, cls, ev, note in rows():
    n += 1; counts[cls] = counts.get(cls, 0) + 1
    out.append(f"| {cond} | {model} | {task} | {sample} | {name} | {cls} | {ev} | {note} |")
out += ["", f"**{n} hidden failures**; by class: " + (", ".join(f"`{k}` {v}" for k, v in sorted(counts.items())) or "none") + "."]
print("\n".join(out))
if any(k == "UNCLASSIFIED" for k in counts):
    sys.exit("unclassified hidden failures: extend CLASSES")
